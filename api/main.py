import math
from typing import Any

from fastapi import FastAPI, Request
from fastapi.encoders import jsonable_encoder
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse

from api.routes.predict import router as predict_router
from api.routes.session import router as session_router

app = FastAPI(
    title="MiDRR API",
    description=(
        "REST API for the MiDRR-Classifier — predicts student disaster preparedness "
        "level (HIGH / MODERATE / LOW) from Minecraft simulation session features."
    ),
    version="0.1.0",
)

app.include_router(predict_router)
app.include_router(session_router)


def _json_safe(value: Any) -> Any:
    """Replace non-finite floats with their string form so the body is valid JSON."""
    if isinstance(value, float) and not math.isfinite(value):
        return str(value)
    if isinstance(value, dict):
        return {k: _json_safe(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_json_safe(v) for v in value]
    return value


@app.exception_handler(RequestValidationError)
async def validation_error_handler(request: Request, exc: RequestValidationError) -> JSONResponse:
    """Same 422 body as FastAPI's default handler, but safe for Infinity/NaN inputs.

    The default handler echoes each rejected ``input`` back to the caller; when
    that input is ``inf``/``nan`` (the JSON literals Infinity/NaN), encoding the
    error itself fails and the client gets a 500 instead of the 422.
    """
    return JSONResponse(status_code=422, content={"detail": _json_safe(jsonable_encoder(exc.errors()))})


@app.get("/health", tags=["health"])
def health() -> dict:
    """Health check endpoint. Returns 200 if the server is running."""
    return {"status": "ok"}
